SHORT = lambda sido: sido[:2] if not sido.startswith('전남광주') else '광주'
ns = lambda x: re.sub(r'\s', '', x)

def locate():
    g = adk.get('20261001', 'emd', detail=True).reset_index(drop=True)
    pts = gpd.GeoDataFrame([{'n': n} for n, *_ in LM], geometry=[Point(lon, lat) for _, _, lat, lon, _ in LM], crs=4326).to_crs(g.crs)
    j = gpd.sjoin(pts, g[['emdnm', 'sggnm', 'sidonm', 'geom']].set_geometry('geom'), how='left', predicate='within')
    out = []
    for (n, k, lat, lon, s), (_, r) in zip(LM, j.iterrows()):
        out.append(dict(n=n, k=k, s=s, emd=r.emdnm, sgg=r.sggnm, sido=r.sidonm))
    return out

def gu_ok(gu, sgg, sido):
    a, b = ns(gu), ns(sgg)
    if a == b or b.startswith(a): return True
    m = re.match(r'^(\S+) (\S+)$', gu)          # '대구 중구', '광주 동구'
    return bool(m and SHORT(sido) == m.group(1) and ns(m.group(2)) == b)

def assign(city, data, L):
    out = []
    for x in L:
        if x['emd'] is None or (SIDO[city] and x['sido'] not in SIDO[city]): continue
        if city == 'korea':
            c = [i for i, d in enumerate(data['d']) if gu_ok(d['n'], x['sgg'], x['sido'])]
        else:
            c = [i for i, d in enumerate(data['d']) if ns(d['n']) == ns(x['emd']) and gu_ok(data['gu'][int(d['g'])]['n'], x['sgg'], x['sido'])]
            if city == 'gwangju' and not c: continue
        if len(c) != 1:
            print('  !', city, x['n'], x['sgg'], x['emd'], 'candidates', [data['d'][i]['n'] for i in c]); continue
        out.append(dict(n=x['n'], k=x['k'], s=x['s'], i=c[0]))
    if city == 'korea':   # 전국 지도는 대표급만 (시군구 하나에 하나)
        by = {}
        for o in out:
            if o['s'] == 2: by.setdefault(o['i'], o)
        out = list(by.values())
    return out

if __name__ == '__main__':
    L = locate()
    for x in L: print('%-14s %-4s %s %s %s' % (x['n'], x['k'], x['sido'], x['sgg'], x['emd']))
